"""Product profiles for the digital-twin simulator.

A profile describes one product category: its Ditto feature schema (properties, units,
valid ranges), the device kinds it contains, how synthetic telemetry evolves over time,
the consistency rules a stored twin must satisfy, and which cross-profile health signals
apply to it. simulator.py generates from profiles; probe.py / fleet.py validate stored
twins against the same definitions, so generator and checker cannot drift apart.

EVERYTHING produced here is SYNTHETIC. Values are bounded and internally consistent so
that data-quality checks are meaningful, but they are not real-world measurements, and
every twin carries `attributes.simulator.synthetic = true` plus a notice saying so.

Adding a category: subclass Profile, fill in the class attributes and the four methods
(init_state / step / render / operational_state), then call register(MyProfile()).
Nothing in simulator.py, probe.py or the API needs to change. See README "Extending the
profile registry".

Randomness: every twin gets its own random.Random seeded from (seed, twin id), so a fixed
seed reproduces the same values regardless of fleet order. Time is passed in (`now`), never
read inside a profile, so tests can drive the generator deterministically.
"""
from __future__ import annotations

import math
import time
from dataclasses import dataclass, field
from typing import Any, Callable

from pydantic import BaseModel, ConfigDict, Field

SYNTHETIC_NOTICE = ("Synthetic telemetry generated by the ditto-chaos simulator for resilience testing. "
                    "Not a real-world sensor measurement.")
DEFINITION_NAMESPACE = "org.dittochaos.sim"
HEARTBEAT_PROPS = ("seq", "sentAt")
# Ditto: each element of a definition identifier must match [_a-zA-Z0-9\-.]+ (namespace:name:version).

# Health signals that mean the same thing across categories. A profile maps each one to a
# feature property for the device kinds where it exists; everywhere else it is NOT
# APPLICABLE -- reported as such, never as zero.
SIGNALS = {
    "battery_pct": {"label": "Battery charge", "unit": "%"},
    "temperature_c": {"label": "Primary temperature", "unit": "°C"},
    "humidity_pct": {"label": "Relative humidity", "unit": "%"},
    "power_w": {"label": "Electrical power", "unit": "W"},
}


# ---------------------------------------------------------------- schema
@dataclass(frozen=True)
class Prop:
    type: str                      # number | integer | boolean | string | array | timestamp
    unit: str | None = None
    min: float | None = None
    max: float | None = None
    enum: tuple | None = None
    nullable: bool = False
    description: str = ""

    def accepts(self, value: Any, now: float) -> bool:
        if value is None:
            return self.nullable
        if self.type in ("number", "integer", "timestamp"):
            if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
                return False
            if self.type == "integer" and not float(value).is_integer():
                return False
            if self.type == "timestamp":
                return 1_500_000_000 <= value <= now + 5          # plausible, never in the future
            return (self.min is None or value >= self.min) and (self.max is None or value <= self.max)
        if self.type == "boolean":
            return isinstance(value, bool)
        if self.type == "string":
            return isinstance(value, str) and (self.enum is None or value in self.enum)
        if self.type == "array":
            return isinstance(value, list) and all(isinstance(v, str) for v in value)
        return False

    def describe(self) -> dict:
        d = {"type": self.type}
        for k in ("unit", "min", "max", "description"):
            if getattr(self, k) not in (None, ""):
                d[k] = getattr(self, k)
        if self.enum:
            d["enum"] = list(self.enum)
        if self.nullable:
            d["nullable"] = True
        return d


def num(lo, hi, unit=None, d=""):
    return Prop("number", unit, lo, hi, description=d)


def integer(lo=0, hi=None, unit=None, d=""):
    return Prop("integer", unit, lo, hi, description=d)


def boolean(d=""):
    return Prop("boolean", description=d)


def enum(*values, d=""):
    return Prop("string", enum=tuple(values), description=d)


def ts(d="", nullable=False):
    return Prop("timestamp", "unix s", nullable=nullable, description=d)


HEARTBEAT_SCHEMA = {"seq": integer(1, d="monotonic per-twin update counter"),
                    "sentAt": ts("when the simulator sent this update")}


@dataclass(frozen=True)
class Rule:
    """A consistency rule over one stored twin. `fn(cur, prev, attrs)` returns True (holds),
    False (violated) or None (cannot be evaluated: an input is missing -- the missing
    property is already reported by the schema check, so it is not double-counted)."""
    id: str
    description: str
    fn: Callable[["View", "View | None", dict], bool | None]
    kinds: tuple[str, ...] | None = None


class View:
    """Read-only accessor over a Ditto `features` object: v("motor.rpm") -> value or None."""

    def __init__(self, features: dict | None):
        self.features = features if isinstance(features, dict) else {}

    def __call__(self, path: str):
        feat, _, prop = path.partition(".")
        f = self.features.get(feat)
        props = f.get("properties") if isinstance(f, dict) else None
        return props.get(prop) if isinstance(props, dict) else None

    def has(self, feature: str) -> bool:
        return isinstance(self.features.get(feature), dict)


def _all(*vals) -> bool:
    return all(v is not None for v in vals)


def _monotonic(path: str, slack: float = 0.0):
    def fn(cur, prev, attrs):
        if prev is None:
            return None
        a, b = prev(path), cur(path)
        if not _all(a, b) or isinstance(a, bool) or isinstance(b, bool):
            return None
        return b >= a - slack
    return fn


def _monotonic_down(path: str, slack: float):
    def fn(cur, prev, attrs):
        if prev is None:
            return None
        a, b = prev(path), cur(path)
        return None if not _all(a, b) else b <= a + slack
    return fn


def _approx(a, b, abs_tol, rel_tol=0.0) -> bool:
    return abs(a - b) <= abs_tol + rel_tol * max(abs(a), abs(b))


class BaseParams(BaseModel):
    model_config = ConfigDict(extra="forbid")
    # Simulated time runs this many times faster than wall-clock time for accumulating
    # quantities (energy, odometer, operating hours, cycle progress) so they visibly move.
    time_scale: float = Field(10.0, ge=1, le=120)


# ---------------------------------------------------------------- profile base
class Profile:
    key = "profile"
    version = "1.0.0"
    title = "Profile"
    product_type = "product"
    id_prefix = "device"
    default_interval_s = 2.0
    # Feature that carries seq/sentAt. "telemetry" is a dedicated feature; the EV profile
    # keeps them in "battery" so twins and probes from the car-only version stay compatible.
    heartbeat_feature = "telemetry"
    features: dict[str, dict[str, Prop]] = {}
    feature_descriptions: dict[str, str] = {}
    kinds: dict[str, tuple[str, ...]] = {}           # device kind -> feature names
    models: dict[str, str] = {}                      # device kind -> model name
    signals: dict[str, dict[str, str]] = {}          # signal -> {kind: "feature.prop"}
    failure_modes: list[str] = []                    # domain context, NOT measurements
    Params: type[BaseParams] = BaseParams
    rules: list[Rule] = []

    # -- schema helpers
    def kind_for(self, index: int) -> str:
        names = list(self.kinds)
        return names[(index - 1) % len(names)]

    def feature_names(self, kind: str) -> tuple[str, ...]:
        names = list(self.kinds[kind])
        if self.heartbeat_feature not in names:
            names.append(self.heartbeat_feature)
        return tuple(names)

    def schema(self, feature: str) -> dict[str, Prop]:
        props = dict(self.features.get(feature, {}))
        if feature == self.heartbeat_feature:
            props.update(HEARTBEAT_SCHEMA)
            if feature == "telemetry":
                props["synthetic"] = boolean("always true: this twin is simulated")
        return props

    def definition(self, feature: str) -> str:
        return f"{DEFINITION_NAMESPACE}:{self.key.replace('_', '-')}-{feature}:{self.version}"

    def thing_definition(self) -> str:
        return f"{DEFINITION_NAMESPACE}:{self.key.replace('_', '-')}:{self.version}"

    def params(self, raw: dict | None) -> BaseParams:
        return self.Params(**(raw or {}))

    # -- generation (override)
    def attributes(self, kind: str, p: BaseParams) -> dict:
        return {}

    def init_state(self, kind: str, rng, p: BaseParams, now: float) -> dict:
        raise NotImplementedError

    def step(self, kind: str, s: dict, rng, dt: float, p: BaseParams, now: float) -> None:
        raise NotImplementedError

    def render(self, kind: str, s: dict, now: float, p: BaseParams) -> dict[str, dict]:
        raise NotImplementedError

    def operational_state(self, kind: str, v: View) -> str | None:
        return None

    # -- validation
    def signal_path(self, signal: str, kind: str) -> str | None:
        return (self.signals.get(signal) or {}).get(kind)

    def signal_applicable(self, signal: str) -> bool:
        return bool(self.signals.get(signal))

    def check(self) -> None:
        """Self-consistency of the definition; called by register()."""
        assert self.kinds, f"{self.key}: no device kinds"
        for kind, feats in self.kinds.items():
            for f in feats:
                assert f in self.features, f"{self.key}/{kind}: unknown feature {f}"
            assert kind in self.models, f"{self.key}/{kind}: no model name"
        for sig, by_kind in self.signals.items():
            assert sig in SIGNALS, f"{self.key}: unknown signal {sig}"
            for kind, path in by_kind.items():
                feat, _, prop = path.partition(".")
                assert feat in self.kinds[kind] and prop in self.schema(feat), f"{self.key}: bad signal path {path}"
        for r in self.rules:
            assert not r.kinds or set(r.kinds) <= set(self.kinds), f"{self.key}: rule {r.id} names unknown kinds"

    def describe(self) -> dict:
        return {
            "key": self.key, "version": self.version, "title": self.title, "product_type": self.product_type,
            "default_id_prefix": self.id_prefix, "default_interval_s": self.default_interval_s,
            "heartbeat_feature": self.heartbeat_feature, "thing_definition": self.thing_definition(),
            "kinds": {k: {"model": self.models[k], "features": list(self.feature_names(k))} for k in self.kinds},
            "features": {f: {"description": self.feature_descriptions.get(f, ""), "definition": self.definition(f),
                             "properties": {n: p.describe() for n, p in self.schema(f).items()}}
                         for f in {*self.features, self.heartbeat_feature}},
            "signals": {s: ({"applicable": True, "paths": self.signals[s]} if self.signal_applicable(s)
                            else {"applicable": False}) for s in SIGNALS},
            "rules": [{"id": r.id, "description": r.description, "kinds": list(r.kinds) if r.kinds else None}
                      for r in self.rules],
            "failure_modes": list(self.failure_modes), "synthetic": True,
            "params_schema": self.Params.model_json_schema(),
        }


# ---------------------------------------------------------------- A. electric vehicles
class EVParams(BaseParams):
    base_lat: float = Field(12.97, ge=-89, le=89)
    base_lon: float = Field(77.59, ge=-179, le=179)
    area_deg: float = Field(0.1, gt=0, le=2)
    battery_capacity_kwh: float = Field(75.0, ge=10, le=200)
    efficiency_km_per_kwh: float = Field(6.5, ge=2, le=12)
    max_speed_kmh: float = Field(120.0, ge=20, le=200)


class ElectricVehicle(Profile):
    key, title, product_type, id_prefix = "ev", "Electric vehicles", "electric_vehicle", "car"
    default_interval_s = 2.0
    heartbeat_feature = "battery"
    features = {
        "battery": {"level": num(0, 100, "%", "state of charge"), "charging": boolean(),
                    "chargingPowerKw": num(0, 150, "kW"), "rangeKm": num(0, 2400, "km", "estimated remaining range")},
        "location": {"lat": num(-90, 90, "deg"), "lon": num(-180, 180, "deg")},
        "motion": {"speedKmh": num(0, 200, "km/h"), "headingDeg": num(0, 360, "deg"),
                   "odometerKm": num(0, 2_000_000, "km")},
        "thermal": {"batteryTempC": num(-20, 70, "°C"), "cabinTempC": num(-20, 55, "°C")},
        "diagnostics": {"faultActive": boolean(),
                        "faultCode": enum("", "BMS_TEMP_HIGH", "TPMS_LOW", "CHARGER_COMM")},
    }
    feature_descriptions = {"battery": "traction battery", "location": "GNSS position",
                            "motion": "vehicle motion", "thermal": "battery and cabin temperature",
                            "diagnostics": "active vehicle fault"}
    kinds = {"passenger_ev": ("battery", "location", "motion", "thermal", "diagnostics")}
    models = {"passenger_ev": "EV-X"}
    signals = {"battery_pct": {"passenger_ev": "battery.level"},
               "temperature_c": {"passenger_ev": "thermal.batteryTempC"}}
    failure_modes = [
        "stale location breaks dispatch, geofencing and ETA estimates",
        "stale battery level hides vehicles that need charging",
        "lost acknowledged updates can roll back odometer or charge state seen by fleet tools",
    ]
    Params = EVParams
    rules = [
        Rule("ev.charging_stationary", "a charging vehicle reports zero speed",
             lambda c, p, a: None if not _all(c("battery.charging"), c("motion.speedKmh"))
             else (not c("battery.charging")) or c("motion.speedKmh") == 0),
        Rule("ev.charging_power", "charging power is positive exactly when charging",
             lambda c, p, a: None if not _all(c("battery.charging"), c("battery.chargingPowerKw"))
             else c("battery.charging") == (c("battery.chargingPowerKw") > 0)),
        Rule("ev.range_matches_charge", "estimated range matches charge x capacity x efficiency",
             lambda c, p, a: None if not _all(c("battery.level"), c("battery.rangeKm"),
                                              a.get("batteryCapacityKwh"), a.get("efficiencyKmPerKwh"))
             else _approx(c("battery.rangeKm"),
                          c("battery.level") / 100 * a["batteryCapacityKwh"] * a["efficiencyKmPerKwh"], 5, 0.05)),
        Rule("ev.fault_code_consistent", "faultActive is true exactly when a fault code is set",
             lambda c, p, a: None if not _all(c("diagnostics.faultActive"), c("diagnostics.faultCode"))
             else c("diagnostics.faultActive") == (c("diagnostics.faultCode") != "")),
        Rule("ev.in_service_area", "position stays inside the configured service area",
             lambda c, p, a: None if not _all(c("location.lat"), c("location.lon"), a.get("serviceArea"))
             else abs(c("location.lat") - a["serviceArea"]["lat"]) <= a["serviceArea"]["radiusDeg"] * 1.5
             and abs(c("location.lon") - a["serviceArea"]["lon"]) <= a["serviceArea"]["radiusDeg"] * 1.5),
        Rule("ev.odometer_monotonic", "odometer never decreases", _monotonic("motion.odometerKm")),
    ]

    def attributes(self, kind, p):
        return {"batteryCapacityKwh": p.battery_capacity_kwh, "efficiencyKmPerKwh": p.efficiency_km_per_kwh,
                "serviceArea": {"lat": p.base_lat, "lon": p.base_lon, "radiusDeg": p.area_deg}}

    def init_state(self, kind, rng, p, now):
        return {"level": rng.uniform(40, 100), "charging": False, "cpow": 0.0, "target": 90.0,
                "lat": p.base_lat + rng.uniform(-p.area_deg, p.area_deg),
                "lon": p.base_lon + rng.uniform(-p.area_deg, p.area_deg),
                "speed": rng.uniform(0, 60), "heading": rng.uniform(0, 360), "odo": rng.uniform(500, 80000),
                "btemp": rng.uniform(22, 30), "ctemp": rng.uniform(20, 26), "fault": ""}

    def step(self, kind, s, rng, dt, p, now):
        sim_dt = dt * p.time_scale
        if s["charging"]:
            s["speed"] = 0.0
            s["level"] = min(100.0, s["level"] + s["cpow"] * sim_dt / 3600 / p.battery_capacity_kwh * 100)
            if s["level"] >= s["target"]:
                s["charging"], s["cpow"] = False, 0.0
        else:
            s["speed"] = 0.0 if rng.random() < 0.03 else min(p.max_speed_kmh, max(0.0, s["speed"] + rng.uniform(-8, 8)))
            km = s["speed"] * sim_dt / 3600
            s["odo"] += km
            s["level"] = max(0.0, s["level"] - (km / p.efficiency_km_per_kwh + 0.0005) / p.battery_capacity_kwh * 100)
            # steer back toward the service area centre once outside it
            if abs(s["lat"] - p.base_lat) > p.area_deg or abs(s["lon"] - p.base_lon) > p.area_deg:
                s["heading"] = math.degrees(math.atan2(p.base_lon - s["lon"], p.base_lat - s["lat"])) % 360
            else:
                s["heading"] = (s["heading"] + rng.uniform(-20, 20)) % 360
            s["lat"] += km / 111.0 * math.cos(math.radians(s["heading"]))
            s["lon"] += km / 111.0 * math.sin(math.radians(s["heading"]))
            if s["level"] < rng.uniform(15, 25) and s["speed"] < 5:
                s["charging"], s["speed"] = True, 0.0
                s["cpow"], s["target"] = rng.choice([7.4, 11.0, 22.0, 50.0]), rng.uniform(80, 95)
        target_temp = 22 + s["speed"] / 12 + s["cpow"] / 4
        s["btemp"] += (target_temp - s["btemp"]) * 0.1 + rng.uniform(-0.2, 0.2)
        s["ctemp"] += (22 - s["ctemp"]) * 0.05 + rng.uniform(-0.1, 0.1)
        if s["fault"] == "" and s["btemp"] > 45:
            s["fault"] = "BMS_TEMP_HIGH"
        elif s["fault"] == "" and rng.random() < 0.0005:
            s["fault"] = rng.choice(["TPMS_LOW", "CHARGER_COMM"])
        elif s["fault"] and rng.random() < 0.05 and s["btemp"] < 42:
            s["fault"] = ""

    def render(self, kind, s, now, p):
        return {
            "battery": {"level": round(s["level"], 1), "charging": s["charging"],
                        "chargingPowerKw": round(s["cpow"], 1) if s["charging"] else 0.0,
                        "rangeKm": round(s["level"] / 100 * p.battery_capacity_kwh * p.efficiency_km_per_kwh, 1)},
            "location": {"lat": round(s["lat"], 6), "lon": round(s["lon"], 6)},
            "motion": {"speedKmh": round(s["speed"], 1), "headingDeg": round(s["heading"], 1),
                       "odometerKm": round(s["odo"], 2)},
            "thermal": {"batteryTempC": round(s["btemp"], 1), "cabinTempC": round(s["ctemp"], 1)},
            "diagnostics": {"faultActive": s["fault"] != "", "faultCode": s["fault"]},
        }

    def operational_state(self, kind, v):
        if v("diagnostics.faultActive"):
            return "fault"
        if v("battery.charging"):
            return "charging"
        sp = v("motion.speedKmh")
        return None if sp is None else ("driving" if sp > 0 else "parked")


# ---------------------------------------------------------------- B. industrial machinery
def vibration_zone(rms: float) -> str:
    """ISO 10816-style severity zone for a class II (medium, 15-75 kW) machine: A good,
    B acceptable, C restricted operation, D damage likely. Simplified boundaries."""
    return "A" if rms <= 1.12 else "B" if rms <= 2.8 else "C" if rms <= 7.1 else "D"


class MachineParams(BaseParams):
    rated_rpm: float = Field(1480, ge=100, le=10000)
    rated_current_a: float = Field(32, ge=1, le=500)
    max_motor_temp_c: float = Field(95, ge=40, le=150)
    ambient_c: float = Field(25, ge=-10, le=50)
    vibration_baseline_mm_s: float = Field(1.6, ge=0.2, le=6)


class IndustrialMachine(Profile):
    key, title, product_type, id_prefix = "industrial_machine", "Industrial machinery", "industrial_machine", "machine"
    default_interval_s = 2.0
    features = {
        "motor": {"temperatureC": num(-20, 160, "°C"), "rpm": num(0, 12000, "rpm"),
                  "loadPct": num(0, 100, "%"), "currentA": num(0, 600, "A")},
        "vibration": {"rmsMmS": num(0, 50, "mm/s", "RMS velocity"), "peakMmS": num(0, 120, "mm/s"),
                      "zone": enum("A", "B", "C", "D", d="ISO 10816-style severity zone")},
        "operation": {"status": enum("running", "idle", "fault", "maintenance"),
                      "operatingHours": num(0, 500_000, "h"), "startsCount": integer(0)},
        "diagnostics": {"faultCodes": Prop("array", description="active fault codes"),
                        "activeFaultCount": integer(0, 10), "lastFaultAt": ts(nullable=True)},
    }
    feature_descriptions = {"motor": "drive motor", "vibration": "bearing-housing vibration sensor",
                            "operation": "machine state machine", "diagnostics": "controller fault log"}
    kinds = {"motor_pump": ("motor", "vibration", "operation", "diagnostics")}
    models = {"motor_pump": "IM-500 Motor-Pump"}
    signals = {"temperature_c": {"motor_pump": "motor.temperatureC"}}
    failure_modes = [
        "stale vibration or temperature data delays predictive-maintenance alarms",
        "missed fault-code updates leave a stopped machine looking healthy on dashboards",
        "lost operating-hour updates corrupt maintenance-interval accounting",
    ]
    Params = MachineParams
    rules = [
        Rule("machine.rpm_matches_status", "rpm is positive while running and zero otherwise",
             lambda c, p, a: None if not _all(c("operation.status"), c("motor.rpm"))
             else (c("motor.rpm") > 0) == (c("operation.status") == "running")),
        Rule("machine.current_matches_status", "motor current is drawn only while running",
             lambda c, p, a: None if not _all(c("operation.status"), c("motor.currentA"))
             else (c("motor.currentA") > 0) == (c("operation.status") == "running")),
        Rule("machine.fault_codes_consistent", "fault status implies an active fault code, and the count matches",
             lambda c, p, a: None if not _all(c("operation.status"), c("diagnostics.activeFaultCount"),
                                              c("diagnostics.faultCodes"))
             else c("diagnostics.activeFaultCount") == len(c("diagnostics.faultCodes"))
             and (c("operation.status") != "fault" or c("diagnostics.activeFaultCount") > 0)),
        Rule("machine.vibration_zone", "reported zone matches the RMS velocity",
             lambda c, p, a: None if not _all(c("vibration.rmsMmS"), c("vibration.zone"))
             else vibration_zone(c("vibration.rmsMmS")) == c("vibration.zone")),
        Rule("machine.peak_not_below_rms", "peak vibration is at least the RMS value",
             lambda c, p, a: None if not _all(c("vibration.rmsMmS"), c("vibration.peakMmS"))
             else c("vibration.peakMmS") >= c("vibration.rmsMmS")),
        Rule("machine.rpm_within_rating", "rpm never exceeds 105% of the rated speed",
             lambda c, p, a: None if not _all(c("motor.rpm"), a.get("ratedRpm"))
             else c("motor.rpm") <= a["ratedRpm"] * 1.05),
        Rule("machine.hours_monotonic", "operating hours never decrease", _monotonic("operation.operatingHours")),
        Rule("machine.starts_monotonic", "start count never decreases", _monotonic("operation.startsCount")),
    ]

    def attributes(self, kind, p):
        return {"ratedRpm": p.rated_rpm, "ratedCurrentA": p.rated_current_a, "maxMotorTempC": p.max_motor_temp_c,
                "vibrationClass": "ISO 10816 class II (simplified)"}

    def init_state(self, kind, rng, p, now):
        return {"status": "running", "load": rng.uniform(50, 85), "temp": p.ambient_c + rng.uniform(20, 40),
                "rpm": p.rated_rpm * 0.98, "current": p.rated_current_a * 0.7,
                "rms": p.vibration_baseline_mm_s * rng.uniform(0.8, 1.3), "hours": rng.uniform(100, 30000),
                "starts": rng.randint(10, 2000), "codes": [], "last_fault": None, "wear": 0.0}

    def step(self, kind, s, rng, dt, p, now):
        st = s["status"]
        if st == "running":
            s["load"] = min(100.0, max(20.0, s["load"] + rng.uniform(-4, 4)))
            target = p.ambient_c + (p.max_motor_temp_c - p.ambient_c - 15) * s["load"] / 100
            s["wear"] = min(3.0, s["wear"] + rng.uniform(0, 0.0004) * p.time_scale)
            s["rms"] = max(0.3, p.vibration_baseline_mm_s * (1 + s["wear"]) + rng.uniform(-0.15, 0.15))
            s["hours"] += dt * p.time_scale / 3600
            code = ("E101_MOTOR_OVERTEMP" if s["temp"] > p.max_motor_temp_c else
                    "E205_VIBRATION_HIGH" if s["rms"] > 7.1 else
                    "E301_PHASE_LOSS" if rng.random() < 0.0003 else None)
            if code:
                s.update(status="fault", codes=[code], last_fault=now, rpm=0.0, current=0.0)
            elif rng.random() < 0.01:
                s.update(status="idle", rpm=0.0, current=0.0)
        else:
            s["rpm"], s["current"] = 0.0, 0.0
            target = p.ambient_c
            s["rms"] = max(0.05, rng.uniform(0.05, 0.25))
            if st == "idle" and rng.random() < 0.1:
                s["status"], s["starts"] = "running", s["starts"] + 1
            elif st == "fault" and rng.random() < 0.05:
                s["status"] = "maintenance"
            elif st == "maintenance" and rng.random() < 0.1:
                s.update(status="running", codes=[], wear=0.0, starts=s["starts"] + 1)
        s["temp"] += (target - s["temp"]) * 0.05 + rng.uniform(-0.3, 0.3)
        if s["status"] == "running":   # after any transition, so a (re)started motor reports speed
            s["rpm"] = p.rated_rpm * (1 - 0.03 * s["load"] / 100) + rng.uniform(-3, 3)
            s["current"] = p.rated_current_a * (0.3 + 0.7 * s["load"] / 100) + rng.uniform(-0.3, 0.3)

    def render(self, kind, s, now, p):
        rms = round(s["rms"], 2)
        return {
            "motor": {"temperatureC": round(s["temp"], 1), "rpm": round(s["rpm"], 0) if s["status"] == "running" else 0.0,
                      "loadPct": round(s["load"], 1) if s["status"] == "running" else 0.0,
                      "currentA": round(s["current"], 1) if s["status"] == "running" else 0.0},
            "vibration": {"rmsMmS": rms, "peakMmS": round(rms * 1.414 * 1.2, 2), "zone": vibration_zone(rms)},
            "operation": {"status": s["status"], "operatingHours": round(s["hours"], 3), "startsCount": s["starts"]},
            "diagnostics": {"faultCodes": list(s["codes"]), "activeFaultCount": len(s["codes"]),
                            "lastFaultAt": s["last_fault"]},
        }

    def operational_state(self, kind, v):
        st = v("operation.status")
        return {"fault": "fault", "maintenance": "maintenance"}.get(st, st)


