# US EPA PM2.5 AQI breakpoints (2024 revision): (C_lo, C_hi, I_lo, I_hi).
_PM25_BREAKPOINTS = [(0.0, 9.0, 0, 50), (9.1, 35.4, 51, 100), (35.5, 55.4, 101, 150),
                     (55.5, 125.4, 151, 200), (125.5, 225.4, 201, 300), (225.5, 500.0, 301, 500)]
_AQI_CATEGORIES = [(50, "good"), (100, "moderate"), (150, "unhealthy_for_sensitive_groups"),
                   (200, "unhealthy"), (300, "very_unhealthy"), (500, "hazardous")]


def aqi_from_pm25(pm25: float) -> int:
    c = math.floor(max(0.0, min(500.0, pm25)) * 10) / 10
    for lo, hi, ilo, ihi in _PM25_BREAKPOINTS:
        if c <= hi:
            return round((ihi - ilo) / (hi - lo) * (max(c, lo) - lo) + ilo)
    return 500


def aqi_category(aqi: float) -> str:
    return next(name for limit, name in _AQI_CATEGORIES if aqi <= limit) if aqi <= 500 else "hazardous"


