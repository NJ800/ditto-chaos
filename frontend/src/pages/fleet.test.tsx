describe("filters on monitoring and history", () => {
  it("history sends category, service and twin filters to the backend", async () => {
    mocked.experiments.mockResolvedValue([{ ...summary({ id: "exp-a" }), targets: ["mongodb"], fleet_profiles: ["ev", "industrial_machine"], affected_profiles: ["industrial_machine"], legacy_fleet: null }]);
    const user = userEvent.setup();
    show("/history");
    const row = (await screen.findByText("exp-a")).closest("tr")!;
    expect(within(row).getByText("Industrial machinery")).toBeInTheDocument();
    await user.selectOptions(screen.getByLabelText("Product category filter"), "industrial_machine");
    await waitFor(() => expect(mocked.experiments).toHaveBeenLastCalledWith(expect.anything(), expect.objectContaining({ profile: "industrial_machine" })));
    await user.selectOptions(screen.getByLabelText("Service filter"), "mongodb");
    await waitFor(() => expect(mocked.experiments).toHaveBeenLastCalledWith(expect.anything(), expect.objectContaining({ profile: "industrial_machine", service: "mongodb" })));
    await user.type(screen.getByLabelText("Twin filter"), "org.hackathon:car-001{enter}");
    await waitFor(() => expect(mocked.experiments).toHaveBeenLastCalledWith(expect.anything(), expect.objectContaining({ twin: "org.hackathon:car-001" })));
  });

  it("history labels car-only records instead of claiming no impact", async () => {
    mocked.experiments.mockResolvedValue([{ ...summary({ id: "exp-old" }), fleet_profiles: ["ev"], affected_profiles: [], legacy_fleet: "car-only fleet (inferred)" }]);
    show("/history");
    const row = (await screen.findByText("exp-old")).closest("tr")!;
    expect(within(row).getByText("car-only run")).toBeInTheDocument();
  });

  it("monitoring charts per-category data quality and filters by category", async () => {
    const t = NOW;
    const rows = [row(t - 4, { profiles: PROFILES }), row(t - 2, { profiles: PROFILES })];
    const user = userEvent.setup();
    show("/monitoring", liveState({}, snapshot(t, { rows })));
    const panel = (await screen.findByRole("heading", { name: "Product data quality" })).closest("section")!;
    const select = within(panel).getByLabelText("Product category filter");
    expect(within(select).getByRole("option", { name: "Industrial machinery" })).toBeInTheDocument();
    await user.selectOptions(select, "industrial_machine");
    expect((select as HTMLSelectElement).value).toBe("industrial_machine");
    expect(within(panel).getByRole("link", { name: "Open twin" })).toHaveAttribute("href", "/fleet?twin=");
  });

  it("monitoring says so when rows carry no per-category data", async () => {
    show("/monitoring");
    expect(await screen.findByText(/No per-profile data in this window/)).toBeInTheDocument();
  });
});
