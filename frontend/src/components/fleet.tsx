// Product-aware fleet views. Every number comes from the backend; a metric the backend
// could not measure renders as "not measured", and a signal a product does not have renders
// as "not applicable" -- never as zero.
import { useEffect, useState } from "react";
import { api } from "../api/client";
import type { FleetView, ProfileBlock, ProfileImpact, ProfileWindow, SignalValue } from "../api/types";
import { DASH, humanize, num, pct } from "../lib/format";
import { Badge, Empty, Note, StateBadge } from "./ui";

/** The fleet description, or null when it cannot be loaded (an older backend, or an invalid
 *  fleet configuration): views that only use it for labels and filters degrade quietly. */
export async function optionalFleet(signal: AbortSignal): Promise<FleetView | null> {
  try {
    return (await api.fleet(signal)) ?? null;
  } catch {
    return null;
  }
}

/** Re-render every `ms` milliseconds (for polling loaders). */
export function usePoll(ms: number): number {
  const [tick, setTick] = useState(0);
  useEffect(() => {
    const t = setInterval(() => setTick((n) => n + 1), ms);
    return () => clearInterval(t);
  }, [ms]);
  return tick;
}

export function SyntheticNotice({ text }: { text?: string }) {
  return (
    <Note tone="accent">
      <span className="font-medium text-ink">Synthetic data.</span> {text ?? "Every twin here is generated by the ditto-chaos simulator for resilience testing; values are bounded and internally consistent but are not real-world sensor measurements."}
    </Note>
  );
}

function freshTone(b: ProfileBlock): "ok" | "warn" | "bad" | "muted" {
  if (!b.measured || b.fresh_ratio === null) return "muted";
  if (b.fresh_ratio >= 0.95) return "ok";
  return b.fresh_ratio >= 0.5 ? "warn" : "bad";
}

/** One row per profile: freshness, validity, loss and drift from the newest probe tick. */
export function ProfileHealthTable({ profiles, onSelect, selected }: { profiles: Record<string, ProfileBlock> | null | undefined; onSelect?: (key: string) => void; selected?: string }) {
  const entries = Object.entries(profiles ?? {});
  if (!entries.length) return <Empty>No per-profile measurements yet. Is `python probe.py` running against this fleet?</Empty>;
  return (
    <div className="overflow-x-auto">
      <table className="w-full min-w-[920px] border-collapse text-xs">
        <thead>
          <tr>
            {["Product category", "Twins", "Fresh", "Staleness p95", "Valid", "Lost updates", "Search drift", "Operational states"].map((h) => (
              <th key={h} className="th">
                {h}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {entries.map(([key, b]) => (
            <tr key={key} className={`hover:bg-raised ${selected === key ? "bg-raised" : ""}`}>
              <td className="td">
                {onSelect ? (
                  <button type="button" className="text-left text-accent hover:underline" onClick={() => onSelect(key)}>
                    {b.title}
                  </button>
                ) : (
                  <span className="text-ink">{b.title}</span>
                )}
                <div className="num text-xxs text-faint">{key}{b.interval_s ? ` · every ${b.interval_s}s` : ""}</div>
              </td>
              <td className="td num">
                {b.measured ? `${b.observed ?? DASH}/${b.twins}` : `${b.twins}`}
                {b.measured && (b.missing ?? 0) > 0 && <div className="text-xxs text-bad">{b.missing} missing</div>}
              </td>
              <td className="td">
                {b.measured ? (
                  <>
                    <Badge tone={freshTone(b)}>{pct(b.fresh_ratio, 0)}</Badge>
                    <div className="num mt-0.5 text-xxs text-faint">{b.fresh ?? DASH} fresh, {b.stale ?? DASH} stale</div>
                  </>
                ) : (
                  <span className="text-faint">not measured</span>
                )}
              </td>
              <td className="td num">
                {b.measured ? num(b.stale_p95_s, 1, " s") : <span className="text-faint">not measured</span>}
                <div className="text-xxs text-faint">limit {num(b.freshness_limit_s, 1, " s")}</div>
              </td>
              <td className="td">
                {b.measured && b.valid_ratio !== null ? (
                  <>
                    <Badge tone={b.invalid ? "warn" : "ok"}>{pct(b.valid_ratio, 0)}</Badge>
                    {(b.invalid ?? 0) > 0 && <div className="num mt-0.5 text-xxs text-warn">{b.invalid} invalid{b.violation_count !== undefined ? ` · ${b.violation_count} violations` : ""}</div>}
                  </>
                ) : (
                  <span className="text-faint">not measured</span>
                )}
              </td>
              <td className={`td num ${b.lost_acked ? "text-bad" : ""}`}>{b.lost_acked === null ? <span className="text-faint">unknown</span> : b.lost_acked}</td>
              <td className={`td num ${b.search_drift ? "text-warn" : ""}`}>{b.search_drift === null ? <span className="text-faint">unknown</span> : b.search_drift}</td>
              <td className="td text-dim">
                {Object.keys(b.operational ?? {}).length
                  ? Object.entries(b.operational ?? {})
                      .sort((x, y) => y[1] - x[1])
                      .map(([k, n]) => `${humanize(k)} ${n}`)
                      .join(", ")
                  : DASH}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function signalCell(v: SignalValue | undefined, unit: string) {
  if (!v || !v.applicable) return <span className="text-faint">not applicable</span>;
  if (v.mean === null || v.mean === undefined) return <span className="text-faint">no value this tick</span>;
  return (
    <span className="num">
      {num(v.mean, 1, unit)}
      {v.min !== undefined && v.min !== null && v.max !== undefined && v.max !== null && (
        <span className="text-xxs text-faint">
          {" "}
          ({num(v.min, 1)}–{num(v.max, 1)})
        </span>
      )}
    </span>
  );
}

/** Cross-profile health signals (battery, temperature, humidity, power): fleet mean per
 *  profile, or "not applicable" where that product has no such feature. */
export function SignalsTable({ profiles, signals }: { profiles: Record<string, ProfileBlock> | null | undefined; signals: FleetView["signals"] }) {
  const entries = Object.entries(profiles ?? {});
  if (!entries.length) return <Empty>No per-profile measurements yet.</Empty>;
  const keys = Object.keys(signals);
  return (
    <div className="overflow-x-auto">
      <table className="w-full min-w-[720px] border-collapse text-xs">
        <thead>
          <tr>
            <th className="th">Product category</th>
            {keys.map((k) => (
              <th key={k} className="th">
                {signals[k].label} ({signals[k].unit})
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {entries.map(([key, b]) => (
            <tr key={key}>
              <td className="td text-ink">{b.title}</td>
              {keys.map((k) => (
                <td key={k} className="td">
                  {b.measured ? signalCell(b.signals?.[k], ` ${signals[k].unit}`) : <span className="text-faint">not measured</span>}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function win(w: ProfileWindow | null, f: (w: ProfileWindow) => string) {
  return w && w.measured_samples ? f(w) : "not measured";
}

/** How one experiment affected each product profile, from its own probe ticks. */
export function ProfileImpactTable({ impact, legacy }: { impact: ProfileImpact | null | undefined; legacy?: boolean }) {
  if (!impact) {
    return <Empty>{legacy ? "No per-profile data: this run was recorded before multi-product support (car-only fleet)." : "No per-profile measurements were recorded for this run."}</Empty>;
  }
  const rows = Object.entries(impact.profiles);
  return (
    <div className="space-y-2">
      <div className="overflow-x-auto">
        <table className="w-full min-w-[960px] border-collapse text-xs">
          <thead>
            <tr>
              {["Product category", "Impact", "Symptoms", "Fresh twins (before → fault → recovery)", "Staleness p95 (before → fault)", "Valid (min, before → fault)", "Lost / drift (fault)", "Recovered"].map((h) => (
                <th key={h} className="th">
                  {h}
                </th>
              ))}
            </tr>
          </thead>
          <tbody>
            {rows.map(([key, r]) => (
              <tr key={key}>
                <td className="td">
                  <span className="text-ink">{r.title ?? key}</span>
                  <div className="text-xxs text-faint">
                    {r.twins ?? DASH} twins{impact.scope ? (r.in_scope ? " · in observation scope" : " · outside the scope") : ""}
                  </div>
                </td>
                <td className="td">
                  <StateBadge state={r.status} />
                </td>
                <td className="td text-dim">{r.symptoms.length ? r.symptoms.map(humanize).join(", ") : DASH}</td>
                <td className="td num">
                  {win(r.before, (w) => pct(w.fresh_ratio_mean, 0))} → {win(r.fault, (w) => pct(w.fresh_ratio_mean, 0))} → {win(r.recovery, (w) => pct(w.fresh_ratio_mean, 0))}
                </td>
                <td className="td num">
                  {win(r.before, (w) => num(w.stale_p95_s, 1, " s"))} → {win(r.fault, (w) => num(w.stale_p95_s, 1, " s"))}
                </td>
                <td className="td num">
                  {win(r.before, (w) => pct(w.valid_ratio_min, 0))} → {win(r.fault, (w) => pct(w.valid_ratio_min, 0))}
                </td>
                <td className="td num">{win(r.fault, (w) => `${w.lost_acked_max ?? "unknown"} / ${w.search_drift_max ?? "unknown"}`)}</td>
                <td className="td">{r.recovered === null ? <span className="text-faint">not measured</span> : r.recovered ? <Badge tone="ok">yes</Badge> : <Badge tone="bad">no</Badge>}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      <p className="text-xxs text-faint">
        {impact.system_wide_symptoms.length
          ? `Shared by every measured profile (service-level): ${impact.system_wide_symptoms.map(humanize).join(", ")}. `
          : "No symptom was shared by every measured profile. "}
        {impact.not_measured_profiles.length ? `Not measured during the fault (twin data unreadable): ${impact.not_measured_profiles.join(", ")} -- their impact is unknown, not zero. ` : ""}
        Basis: {impact.basis}.
      </p>
      {rows.some(([, r]) => r.notes.length) && (
        <ul className="list-disc pl-4 text-xxs text-faint">
          {rows.flatMap(([k, r]) => r.notes.map((n, i) => <li key={`${k}${i}`}>{`${r.title ?? k}: ${n}`}</li>))}
        </ul>
      )}
    </div>
  );
}

/** Multi-select of enabled profiles for an experiment's observation scope. */
export function ScopePicker({ fleet, value, onChange }: { fleet: FleetView | null; value: string[]; onChange: (v: string[]) => void }) {
  if (!fleet) return <span className="text-xxs text-faint">fleet not loaded: every profile is observed</span>;
  return (
    <fieldset className="flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-dim">
      <legend className="sr-only">Observation scope</legend>
      {fleet.enabled.map((k) => (
        <label key={k} className="flex items-center gap-1.5">
          <input type="checkbox" checked={value.includes(k)} onChange={(e) => onChange(e.target.checked ? [...value, k] : value.filter((x) => x !== k))} />
          {fleet.registry[k]?.title ?? k}
        </label>
      ))}
    </fieldset>
  );
}
